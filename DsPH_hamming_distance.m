function distances = DsPH_hamming_distance(bitsA, bitsB)
% Compute pairwise Hamming distances between packed binary rows.

lookup = uint8([0 1 1 2 1 2 2 3 1 2 2 3 2 3 3 4 1 2 2 3 2 3 3 4 ...
    2 3 3 4 3 4 4 5 1 2 2 3 2 3 3 4 2 3 3 4 3 4 4 5 2 3 3 4 ...
    3 4 4 5 3 4 4 5 4 5 5 6 1 2 2 3 2 3 3 4 2 3 3 4 3 4 4 5 ...
    2 3 3 4 3 4 4 5 3 4 4 5 4 5 5 6 2 3 3 4 3 4 4 5 3 4 4 5 ...
    4 5 5 6 2 3 3 4 3 4 4 5 3 4 4 5 4 5 5 6 3 4 4 5 4 5 5 6 ...
    4 5 5 6 5 6 6 7 1 2 2 3 2 3 3 4 2 3 3 4 3 4 4 5 2 3 3 4 ...
    3 4 4 5 3 4 4 5 4 5 5 6 2 3 3 4 3 4 4 5 3 4 4 5 4 5 5 6 ...
    4 5 5 6 5 6 6 7 2 3 3 4 3 4 4 5 3 4 4 5 4 5 5 6 4 5 5 6 ...
    5 6 6 7 3 4 4 5 4 5 5 6 4 5 5 6 5 6 6 7 4 5 5 6 5 6 6 7 ...
    5 6 6 7 6 7 7 8]);

distances = zeros(size(bitsA, 1), size(bitsB, 1), 'uint16');
for rowIndex = 1:size(bitsA, 1)
    for wordIndex = 1:size(bitsA, 2)
        xorValues = bitxor(bitsA(rowIndex, wordIndex), bitsB(:, wordIndex));
        distances(rowIndex, :) = distances(rowIndex, :) + ...
            uint16(lookup(xorValues + 1));
    end
end
end